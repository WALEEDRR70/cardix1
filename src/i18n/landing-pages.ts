export function getLandingPage(slug: string): LandingPage | undefined {
  return LANDING_PAGES.find((p) => p.slug === slug);
}

export function getLandingCopy(page: LandingPage, lang: Locale): LandingCopy {
  return page.copy[lang] ?? page.copy.en!;
}

export function getAllLandingSlugs(): string[] {
  return LANDING_PAGES.map((p) => p.slug);
}

export function getLandingPagesByCategory() {
  const byCat: Record<LandingCategory, LandingPage[]> = {
    app: [], qr: [], nfc: [], ocr: [], share: [], templates: [], compare: [],
  };
  for (const p of LANDING_PAGES) byCat[p.category].push(p);
  return byCat;
}

