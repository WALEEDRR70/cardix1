/**
 * Translates every English SEO landing page into the remaining locales and writes
 * src/i18n/landing-locales.ts. Run with: bun scripts/landing-translate.ts [locale ...]
 * Uses the project's OpenAI key when available, otherwise the built-in gateway.
 */
import { LANDING_PAGES, type LandingCopy } from "../src/i18n/landing-pages";

const ALL_LOCALES = [
  "fr", "de", "es", "it", "pt", "ru", "tr", "nl",
  "pl", "zh", "zh-TW", "ja", "ko", "hi", "id", "ms", "th", "vi",
] as const;

const NAMES: Record<string, string> = {
  fr: "French", de: "German", es: "Spanish", it: "Italian",
  pt: "Portuguese", ru: "Russian", tr: "Turkish", nl: "Dutch", pl: "Polish",
  zh: "Simplified Chinese", "zh-TW": "Traditional Chinese", ja: "Japanese",
  ko: "Korean", hi: "Hindi", id: "Indonesian", ms: "Malay", th: "Thai", vi: "Vietnamese",
};

const openaiKey = process.env.OPENAI_API_KEY;
const key = openaiKey ?? process.env.LOVABLE_API_KEY;
if (!key) throw new Error("Missing OPENAI_API_KEY / LOVABLE_API_KEY");
const ENDPOINT = openaiKey
  ? "https://api.openai.com/v1/chat/completions"
  : "https://ai.gateway.lovable.dev/v1/chat/completions";
const MODEL = openaiKey ? "gpt-4o-mini" : "google/gemini-3.6-flash";

const args = process.argv.slice(2).filter((a) => (ALL_LOCALES as readonly string[]).includes(a));
const LOCALES = args.length ? args : [...ALL_LOCALES];

const OUT_DIR = "src/i18n/landing-locales";

async function translatePage(locale: string, slug: string, copy: LandingCopy, attempt = 0): Promise<LandingCopy> {
  const res = await fetch(ENDPOINT, {
    method: "POST",
    headers: { Authorization: `Bearer ${key}`, "Content-Type": "application/json" },
    body: JSON.stringify({
      model: MODEL,
      messages: [
        {
          role: "system",
          content:
            `You are a professional SEO localizer for Cardixn, a premium digital business card SaaS. ` +
            `Translate every string value of the given JSON landing page from English into ${NAMES[locale]}. ` +
            `Rules: keep the exact JSON shape and keys; keep "Cardixn", brand names, competitor names, URLs and ` +
            `technical tokens (NFC, QR, OCR, CSV, SEO, vCard, CRM, API, SSO, RFP, KPI) untouched; translate ` +
            `idiomatically for search intent, not literally; keep "title" under 60 characters and "description" ` +
            `under 155 characters; keep CTA buttons short (1-3 words). Reply with JSON only.`,
        },
        { role: "user", content: JSON.stringify(copy) },
      ],
      response_format: { type: "json_object" },
    }),
  });
  if (!res.ok) {
    if (attempt < 4) {
      await new Promise((r) => setTimeout(r, 1500 * (attempt + 1)));
      return translatePage(locale, slug, copy, attempt + 1);
    }
    throw new Error(`${locale}/${slug}: ${res.status} ${await res.text()}`);
  }
  const json = (await res.json()) as { choices?: { message?: { content?: string } }[] };
  const text = json.choices?.[0]?.message?.content ?? "";
  try {
    const parsed = JSON.parse(text) as LandingCopy;
    if (!parsed.title || !Array.isArray(parsed.faqs)) throw new Error("shape");
    return parsed;
  } catch {
    if (attempt < 4) return translatePage(locale, slug, copy, attempt + 1);
    throw new Error(`${locale}/${slug}: unparsable`);
  }
}

async function pool<T>(items: T[], size: number, fn: (item: T) => Promise<void>) {
  let i = 0;
  await Promise.all(
    Array.from({ length: size }, async () => {
      while (i < items.length) {
        const item = items[i++];
        await fn(item);
      }
    }),
  );
}

async function writeIndex() {
  const present = ALL_LOCALES.filter((l) => Bun.file(`${OUT_DIR}/${l}.json`).size > 0);
  const body =
    `// AUTO-GENERATED by scripts/landing-translate.ts — do not edit.\n` +
    `import type { Locale } from "@/i18n/config";\n` +
    `import type { LandingCopy } from "@/i18n/landing-pages";\n` +
    present.map((l) => `import ${l.replace("-", "_")} from "./${l}.json";`).join("\n") +
    `\n\nexport const LANDING_LOCALES: Partial<Record<Locale, Record<string, LandingCopy>>> = {\n` +
    present.map((l) => `  "${l}": ${l.replace("-", "_")} as Record<string, LandingCopy>,`).join("\n") +
    `\n};\n`;
  await Bun.write(`${OUT_DIR}/index.ts`, body);
}

for (const locale of LOCALES) {
  const out: Record<string, LandingCopy> = {};
  const pages = LANDING_PAGES.filter((p) => p.copy.en);
  await pool(pages, 6, async (page) => {
    out[page.slug] = await translatePage(locale, page.slug, page.copy.en!);
  });
  await Bun.write(`${OUT_DIR}/${locale}.json`, JSON.stringify(out, null, 0));
  await writeIndex();
  console.log("done", locale, Object.keys(out).length);
}
