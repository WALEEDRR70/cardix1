/**
 * Translates the English blog articles into every supported locale and writes
 * src/i18n/blog-locales.ts. Run with: bun scripts/blog-translate.ts
 */
import { BLOG_POSTS, type BlogCopy } from "../src/i18n/blog-posts";

const LOCALES = [
  "fr", "de", "es", "it", "pt", "ru", "tr", "nl",
  "pl", "zh", "zh-TW", "ja", "ko", "hi", "id", "ms", "th", "vi",
] as const;

const NAMES: Record<string, string> = {
  fr: "French", de: "German", es: "Spanish", it: "Italian",
  pt: "Portuguese", ru: "Russian", tr: "Turkish", nl: "Dutch", pl: "Polish",
  zh: "Simplified Chinese", "zh-TW": "Traditional Chinese", ja: "Japanese",
  ko: "Korean", hi: "Hindi", id: "Indonesian", ms: "Malay", th: "Thai", vi: "Vietnamese",
};

const key = process.env.LOVABLE_API_KEY;
if (!key) throw new Error("Missing LOVABLE_API_KEY");

async function translatePost(locale: string, copy: BlogCopy, attempt = 0): Promise<BlogCopy> {
  const res = await fetch("https://ai.gateway.lovable.dev/v1/chat/completions", {
    method: "POST",
    headers: { Authorization: `Bearer ${key}`, "Content-Type": "application/json" },
    body: JSON.stringify({
      model: "google/gemini-2.5-flash",
      messages: [
        {
          role: "system",
          content:
            `You are a professional localizer translating long-form marketing/SEO articles for Cardixn, a premium digital business card SaaS. ` +
            `Translate every string value of the given JSON article from English into ${NAMES[locale]}. Rules: keep the exact JSON shape and keys; ` +
            `keep "Cardixn", brand names, URLs and technical tokens (NFC, QR, OCR, CSV, SEO, ESG, CO2, vCard) untouched; translate naturally and idiomatically, not literally; ` +
            `preserve paragraph breaks (\\n\\n) and numbered lists exactly; keep the title under 60 characters and the description under 155 characters where possible; ` +
            `localize "14 min read" style reading times into the target language. Reply with JSON only.`,
        },
        { role: "user", content: JSON.stringify(copy) },
      ],
      response_format: { type: "json_object" },
    }),
  });
  if (!res.ok) {
    if (attempt < 4) {
      await new Promise((r) => setTimeout(r, 3000 * (attempt + 1)));
      return translatePost(locale, copy, attempt + 1);
    }
    throw new Error(`${locale}: ${res.status} ${await res.text()}`);
  }
  const json = await res.json();
  const text = json.choices?.[0]?.message?.content ?? "{}";
  let out: BlogCopy;
  try {
    out = JSON.parse(text);
  } catch {
    if (attempt < 4) return translatePost(locale, copy, attempt + 1);
    throw new Error(`${locale}: unparsable`);
  }
  if (!out?.title || !Array.isArray(out.sections) || out.sections.length !== copy.sections.length) {
    if (attempt < 4) return translatePost(locale, copy, attempt + 1);
    return copy;
  }
  return out;
}

const result: Record<string, Record<string, BlogCopy>> = {};

for (const locale of LOCALES) {
  result[locale] = {};
  await Promise.all(
    BLOG_POSTS.map(async (post) => {
      const en = post.copy.en!;
      result[locale][post.slug] = await translatePost(locale, en);
    }),
  );
  console.log("done", locale);
}

const header = `// AUTO-GENERATED by scripts/blog-translate.ts — do not edit by hand.
// Blog article copy for every non-authored locale.
import type { BlogCopy } from "@/i18n/blog-posts";

export const BLOG_LOCALES: Record<string, Record<string, BlogCopy>> = ${JSON.stringify(result, null, 2)};
`;
await Bun.write("src/i18n/blog-locales.ts", header);
console.log("written");
